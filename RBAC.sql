GRANT SELECT ON FUTURE MATERIALIZED VIEWS IN SCHEMA HOSPITAL_DW.MART TO ROLE HOSPITAL_MANAGER_ROLE;


-- ANALYST ROLE ACCESS
GRANT USAGE ON WAREHOUSE HOSPITAL_WH TO ROLE HOSPITAL_ANALYST_ROLE;
GRANT USAGE ON DATABASE HOSPITAL_DW  TO ROLE HOSPITAL_ANALYST_ROLE;

